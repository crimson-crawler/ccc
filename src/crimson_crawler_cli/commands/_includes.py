def describe(family: str, *, default_label: str = "Defaults") -> str:
    """Describe the accepted and default values for this endpoint family."""
    allowed = globals()[f"{family}_INCLUDES"]
    defaults = globals()[f"{family}_DEFAULTS"]
    text = f"Options: {', '.join(allowed)}. {default_label}: {', '.join(defaults)}."
    restricted = sorted(_RESTRICTED.intersection(allowed) - set(defaults))
